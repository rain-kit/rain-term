/** auto 跟随界面明暗。 */
export function terminalTheme(scheme: ColorScheme, dark: boolean): ITheme {
  if (scheme === "auto") return dark ? oneDark : light;
  return themes[scheme] ?? oneDark;
}

/** 配色是否为浅色背景，用来选搜索高亮等颜色。 */
export function isLightScheme(scheme: ColorScheme, dark: boolean) {
  return scheme === "solarizedLight" || (scheme === "auto" && !dark);
}
